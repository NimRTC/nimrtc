#!/usr/bin/env python3
"""
scripts/check_api_manifest.py
=============================
Verify that the checked-in public-header manifest matches the header set
that is actually on disk.

Why a manifest and not a count
------------------------------
`tests/test_api_classification.cpp::total_header_count_matches_baseline`
asserts that the *number* of public headers equals a baseline constant.
A count cannot tell a swap from a change: deleting `a.hpp` and adding
`b.hpp` in the same PR leaves the count untouched, so CI stays green
while the public surface has moved.  ADR-015 calls the public surface a
*contract*, and a contract needs the actual list, not its cardinality.

The manifest
------------
`docs/api/public_headers.manifest` is a sorted, one-path-per-line list
of every public header, relative to the repository root and using '/'
separators.  It is generated by this script with `--write` and checked
by this script without it.

Usage:
    python scripts/check_api_manifest.py              # check (CI gate)
    python scripts/check_api_manifest.py --write      # regenerate
    python scripts/check_api_manifest.py --list       # print the set

Exit codes:
    0  the manifest matches the tree
    1  the manifest drifted (added / removed / renamed headers)
    2  the manifest file is missing or malformed
"""

from __future__ import annotations

import argparse
import pathlib
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = REPO_ROOT / "src"
MANIFEST = REPO_ROOT / "docs" / "api" / "public_headers.manifest"

SKIP_DIR_PARTS = {"third_party", "build", ".git"}


def collect_headers() -> list[str]:
    """Every public header, relative to the repo root, '/'-separated.

    The selection rule matches the one the ADR-015 gates already use:
    a `.hpp` under `src/**/include/nimrtc/**`, excluding `src/third_party`.
    """
    found: list[str] = []
    for path in SRC.rglob("*.hpp"):
        rel = path.relative_to(REPO_ROOT)
        if any(part in SKIP_DIR_PARTS for part in rel.parts):
            continue
        posix = rel.as_posix()
        if "/include/nimrtc/" not in posix:
            continue
        found.append(posix)
    return sorted(found)


def read_manifest() -> list[str]:
    if not MANIFEST.exists():
        print(f"ERROR: manifest not found: {MANIFEST}", file=sys.stderr)
        print("       generate it with: python scripts/check_api_manifest.py --write",
              file=sys.stderr)
        sys.exit(2)
    entries: list[str] = []
    for lineno, raw in enumerate(MANIFEST.read_text(encoding="utf-8").splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        entries.append(line)
    if not entries:
        print(f"ERROR: manifest is empty: {MANIFEST}", file=sys.stderr)
        sys.exit(2)
    return entries


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--write", action="store_true",
                    help="regenerate the manifest from the current tree")
    ap.add_argument("--list", action="store_true",
                    help="print the header set the tree currently has")
    args = ap.parse_args()

    actual = collect_headers()

    if args.list:
        for p in actual:
            print(p)
        return 0

    if args.write:
        MANIFEST.parent.mkdir(parents=True, exist_ok=True)
        header = (
            "# Public-header manifest -- ADR-015 \"API stability policy\".\n"
            "#\n"
            "# Every public header of the NimRTC API surface, one relative\n"
            "# path per line, sorted, '/'-separated.  This file is the\n"
            "# frozen baseline of the surface: `scripts/check_api_manifest.py`\n"
            "# fails when the tree's header set drifts from it, so a header\n"
            "# cannot be added, removed or renamed without the change being\n"
            "# deliberate and reviewed.\n"
            "#\n"
            "# Regenerate with: python scripts/check_api_manifest.py --write\n"
            "#\n"
            "# count: %d\n"
            "\n" % len(actual)
        )
        MANIFEST.write_text(header + "\n".join(actual) + "\n", encoding="utf-8")
        print(f"wrote {len(actual)} headers to {MANIFEST.relative_to(REPO_ROOT)}")
        return 0

    expected = read_manifest()
    expected_set = set(expected)
    actual_set = set(actual)

    # A duplicate in the manifest means the file was hand-edited badly.
    if len(expected) != len(expected_set):
        dupes = sorted({p for p in expected if expected.count(p) > 1})
        print("ERROR: duplicate entries in the manifest:", file=sys.stderr)
        for d in dupes:
            print(f"  {d}", file=sys.stderr)
        return 2

    added = sorted(actual_set - expected_set)
    removed = sorted(expected_set - actual_set)

    if not added and not removed:
        print(f"[api-manifest] OK: {len(actual_set)} public headers match the manifest")
        return 0

    print("ERROR: the public-header manifest drifted from the tree.",
          file=sys.stderr)
    if added:
        print(f"  {len(added)} header(s) ADDED (not in the manifest):",
              file=sys.stderr)
        for p in added:
            print(f"    + {p}", file=sys.stderr)
    if removed:
        print(f"  {len(removed)} header(s) REMOVED (in the manifest, gone from the tree):",
              file=sys.stderr)
        for p in removed:
            print(f"    - {p}", file=sys.stderr)
    print(file=sys.stderr)
    print("If the change is intentional, regenerate the manifest in the same PR:",
          file=sys.stderr)
    print("    python scripts/check_api_manifest.py --write", file=sys.stderr)
    print("and record the reason in CHANGELOG.md (ADR-015).", file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main())
